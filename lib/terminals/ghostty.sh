#!/usr/bin/env bash
# Ghostty terminal backend
# Config format: key = value
#
# Writes two files per apply:
#   current.conf - terminal font (font-family, font-size)
#   current.css  - tab label font (font-family, font-size for tabbar labels)
#
# The CSS file is referenced from main ghostty config via:
#   gtk-custom-css = fonts/current.css
# It merges with any other gtk-custom-css file, such as one setting colors, via
# ghostty's repeatable gtk-custom-css handling.

GHOSTTY_CONFIG_DIR="$HOME/.config/ghostty/fonts"
GHOSTTY_CONFIG_FILE="$GHOSTTY_CONFIG_DIR/current.conf"
GHOSTTY_CSS_FILE="$GHOSTTY_CONFIG_DIR/current.css"

ghostty_get_font() {
  if [[ -f "$GHOSTTY_CONFIG_FILE" ]]; then
    font_trim "$(grep "^font-family" "$GHOSTTY_CONFIG_FILE" 2>/dev/null | cut -d= -f2 | tr -d '"')"
  else
    echo ""
  fi
}

ghostty_get_size() {
  if [[ -f "$GHOSTTY_CONFIG_FILE" ]]; then
    font_trim "$(grep "^font-size" "$GHOSTTY_CONFIG_FILE" 2>/dev/null | cut -d= -f2)"
  else
    echo ""
  fi
}

# Write tab label font CSS. Rules target libadwaita AdwTabBar selectors
# (tabbar > tabbox > tab > label). Merges with other gtk-custom-css files via
# ghostty's multiple gtk-custom-css file loading.
ghostty_write_css() {
  local font="$1"
  local size="$2"

  cat >"$GHOSTTY_CSS_FILE" <<EOF
/* Ghostty tab font — generated by font tool.
 * Merges with any other gtk-custom-css file the config loads.
 */
tabbar tabbox tab label,
tabbar tabbox tab .title {
  font-family: "${font}";
  font-size: ${size}pt;
}
EOF
}

ghostty_set_font() {
  local font="$1"
  local size
  size=$(ghostty_get_size)
  [[ -z "$size" ]] && size=17

  mkdir -p "$GHOSTTY_CONFIG_DIR"

  cat >"$GHOSTTY_CONFIG_FILE" <<EOF
font-family = "${font}"
font-size = ${size}
window-title-font-family = "${font}"
EOF

  ghostty_write_css "$font" "$size"
}

ghostty_set_size() {
  local size="$1"
  local font
  font=$(ghostty_get_font)
  [[ -z "$font" ]] && font="monospace"

  mkdir -p "$GHOSTTY_CONFIG_DIR"

  cat >"$GHOSTTY_CONFIG_FILE" <<EOF
font-family = "${font}"
font-size = ${size}
window-title-font-family = "${font}"
EOF

  ghostty_write_css "$font" "$size"
  ghostty_reload
}

# Ghostty's GTK app exports a reload-config action on the session bus, and an
# open window redraws in the new font when it runs. Calling the bus name of a
# Ghostty that is not running would start one, hence the pgrep. SIGUSR2 also
# reloads the GTK app, but it ends any Ghostty built without a handler for it.
# macOS has no session bus, so there Ghostty shows the font at its next config
# reload or in a new window.
ghostty_reload() {
  [[ "$(uname -s)" == "Linux" ]] || return 0
  pgrep -x ghostty >/dev/null 2>&1 || return 0
  command -v gdbus >/dev/null 2>&1 || return 0
  gdbus call --session --dest com.mitchellh.ghostty --object-path /com/mitchellh/ghostty \
    --method org.gtk.Actions.Activate reload-config '[]' '{}' >/dev/null 2>&1 || true
}

ghostty_apply() {
  local font="$1"
  ghostty_set_font "$font"
  ghostty_reload
}
